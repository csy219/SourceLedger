# ### 一、先讲清楚：「压测」是什么

# 压测 = **压力测试（Load/Performance Testing）**，通俗说就是：
# **模拟大量用户同时并发请求，持续打你的服务，测出服务的性能上限、稳定性和瓶颈**。

# 核心要回答这些问题：

# - 你的接口每秒能扛多少请求（QPS）？
# - 高并发下请求延迟是多少？平均多久返回？P95/P99 长尾延迟多少？
# - 并发上去之后会不会报错？错误率多少？
# - 服务最多能撑多少并发用户？再高会不会崩？
# - 性能瓶颈在哪？是框架慢、数据库慢、还是下游模型慢？

# 这是后端服务上线前的标准操作，用来验证服务能不能扛住线上的流量，也用来指导扩容优化。

