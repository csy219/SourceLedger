# ### 四、压测一般统计哪些指标

# 对应你说的「token 和延迟」，压测通常会关注这些核心指标：

# 表格

# | 指标 | 含义 | 模拟压测的价值 |
# | --- | --- | --- |
# | QPS | 每秒处理的请求数 | 测出 API 服务的理论吞吐上限 |
# | 平均延迟 | 每个请求平均耗时 | 测出 API 层本身的基础开销 |
# | P95/P99 延迟 | 95%/99% 的请求在多少毫秒内返回 | 评估长尾稳定性，有没有偶发卡顿 |
# | 错误率 | 失败请求占比 | 验证高并发下会不会出错，比如数据库连接池耗尽 |
# | 流式首包延迟 | 流式接口第一个事件多久返回 | 验证流式输出的响应速度 |
# | Token 吞吐 | 每秒能输出多少 token | 验证流式输出的性能 |

