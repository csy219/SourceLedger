# ### 三、为什么一定要单独做这个「压测专用版」？核心价值是「隔离变量」

# 压测的目标如果是**测 API 服务本身的性能**，就必须把下游大模型这个最大的变量去掉，否则压测结果毫无意义。

# #### 1.  精准定位瓶颈：只测 API 层，不测模型

# 如果用真实大模型压测：

# - 大模型本身一次生成就要几百毫秒到几秒，瓶颈完全在模型那边；
# - 你永远不知道 API 框架本身、数据库持久化、幂等逻辑、流式输出这些代码写得好不好、扛不扛打。

# 用模拟函数压测：

# - 模型 / 检索的耗时被完全剔除，压出来的就是**API 服务本身的纯性能基线**；
# - 如果这个基线 QPS 是 500，线上真实 QPS 只有 50，那瓶颈肯定在下游模型 / 检索，不在 API 代码；
# - 优化代码的时候，也能用这个基线验证优化有没有效果。

# #### 2.  成本极低：不用烧钱调用大模型

# 压测通常要发起几万、几十万次请求：

# - 真调用大模型，费用会非常高；
# - 而且大模型服务商一般都有速率限制，你根本压不上去，还没到 API 的瓶颈，模型那边先限流了。

# 模拟函数零成本，想压多少压多少，完全不受外部限制。

# #### 3.  结果稳定可复现

# 真实大模型每次回答长度、生成速度都不一样，压测结果波动很大，这次和上次跑出来差 30% 都很正常，没法判断是代码优化了还是模型波动了。

# 模拟函数返回完全固定，每次压测结果高度一致，可以精准对比：

# - 改了一版代码，性能提升了还是下降了；
# - 加了数据库持久化，延迟增加了多少；
# - 开了幂等校验，QPS 掉了多少。

# #### 4.  环境要求低，方便集成 CI

# 压测环境不需要部署大模型、向量库、知识库这些重型依赖，只要起一个 API 服务就能跑。
# 可以很方便地集成到 CI/CD 流水线里，每次代码提交自动跑性能门禁，性能掉了直接拦截。

