# ### 五、总结

# 这个文件本质就是一个**性能测试专用的 Mock 应用**：

# - 复用 100% 的 API 层代码（路由、参数校验、幂等、状态持久化、流式输出、数据库 / Redis 全部都在）；
# - 只把最核心、最慢、最贵的大模型调用，替换成了固定返回的模拟函数；
# - 目的就是测出「API 服务本身的纯性能基线」，作为服务性能的基准参考。

# 后续线上真实环境的性能和这个基线对比，就能快速判断瓶颈是在自身代码还是下游依赖。